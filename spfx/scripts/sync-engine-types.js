/**
 * Keeps the web part's report types and bundled sample data in sync with the
 * engine, so there's one source of truth.
 *
 *   1. Regenerates models/sampleData.ts from prototype/sample-reports.json
 *      (run `node prototype/generate-sample.js` in the repo root first).
 *   2. Reminds you to reconcile models/report.ts with src/engine/results.ts
 *      (the passive type copy — kept manual because it's tiny and rarely changes).
 *
 * Usage (from spfx/):  npm run sync-engine-types
 */
const fs = require("fs");
const path = require("path");

const repoRoot = path.join(__dirname, "..", "..");
const samplePath = path.join(repoRoot, "prototype", "sample-reports.json");
const outPath = path.join(__dirname, "..", "src", "webparts", "bcbaCompliance", "models", "sampleData.ts");

if (!fs.existsSync(samplePath)) {
  console.error("Missing prototype/sample-reports.json — run `node prototype/generate-sample.js` in the repo root first.");
  process.exit(1);
}
const data = fs.readFileSync(samplePath, "utf8");
const header =
  'import { BcbaReport } from "./report";\n\n' +
  "/**\n" +
  " * Bundled example data for the local workbench and the no-row-yet fallback.\n" +
  " * Generated by scripts/sync-engine-types.js from prototype/sample-reports.json.\n" +
  " */\n" +
  "export const SAMPLE_REPORTS: BcbaReport[] = ";
fs.writeFileSync(outPath, header + data + ";\n");
console.log("Updated", path.relative(process.cwd(), outPath));
console.log("Reminder: if src/engine/results.ts changed shape, mirror it in models/report.ts.");
